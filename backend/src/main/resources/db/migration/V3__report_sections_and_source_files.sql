-- 2. Source Files (Raw Upload Metadata - file content stored immutably on disk)
CREATE TABLE source_file (
    id UUID PRIMARY KEY,
    original_filename VARCHAR(255) NOT NULL,
    storage_path VARCHAR(500) NOT NULL UNIQUE,
    file_size_bytes BIGINT NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    file_extension VARCHAR(20) NOT NULL,
    sha256_checksum VARCHAR(64) NOT NULL,
    uploaded_by VARCHAR(255) NOT NULL,
    uploaded_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_source_file_checksum ON source_file(sha256_checksum);
CREATE INDEX idx_source_file_uploaded_at ON source_file(uploaded_at);

-- 3. Import Batches
CREATE TABLE import_batch (
    id UUID PRIMARY KEY,
    report_section_id VARCHAR(50) NOT NULL,
    source_file_id UUID NOT NULL,
    status VARCHAR(50) NOT NULL,
    version_number BIGINT NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT FALSE,
    active_section_id VARCHAR(50),
    total_rows INT DEFAULT 0,
    accepted_rows INT DEFAULT 0,
    rejected_rows INT DEFAULT 0,
    error_message VARCHAR(2000),
    error_details CLOB,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE,
    completed_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_import_batch_section FOREIGN KEY (report_section_id) REFERENCES report_section(id),
    CONSTRAINT fk_import_batch_file FOREIGN KEY (source_file_id) REFERENCES source_file(id),
    CONSTRAINT fk_import_batch_active_section FOREIGN KEY (active_section_id) REFERENCES report_section(id),
    -- Portable DB-level guarantee: at most ONE active batch per report section (NULLs are permitted and non-unique)
    CONSTRAINT uq_import_batch_active_section UNIQUE (active_section_id),
    -- Consistency check: active batch must match its section and must be COMMITTED; inactive batch must have NULL active_section_id
    CONSTRAINT chk_import_batch_active_status CHECK (
        (is_active = FALSE AND active_section_id IS NULL) OR 
        (is_active = TRUE AND active_section_id = report_section_id AND status = 'COMMITTED')
    ),
    -- Extra safety: FAILED batch can never be active
    CONSTRAINT chk_import_batch_failed_not_active CHECK (
        status <> 'FAILED' OR is_active = FALSE
    )
);

CREATE INDEX idx_import_batch_section_created ON import_batch(report_section_id, created_at DESC);
CREATE INDEX idx_import_batch_status ON import_batch(status);
CREATE INDEX idx_import_batch_active ON import_batch(report_section_id, is_active);

-- 4. Structured Import Stage Durations (Queryable operational metrics per batch stage)
CREATE TABLE import_batch_stage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id UUID NOT NULL,
    stage VARCHAR(50) NOT NULL,
    status VARCHAR(50) NOT NULL,
    duration_ms BIGINT NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    details VARCHAR(1000),
    CONSTRAINT fk_import_batch_stage_batch FOREIGN KEY (batch_id) REFERENCES import_batch(id) ON DELETE CASCADE,
    CONSTRAINT uq_import_batch_stage UNIQUE (batch_id, stage)
);

CREATE INDEX idx_import_batch_stage_batch_id ON import_batch_stage(batch_id);
