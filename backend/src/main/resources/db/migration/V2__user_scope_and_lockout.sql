-- 1. Add account lockout and failed attempt tracking to app_user
ALTER TABLE app_user ADD COLUMN failed_attempt_count INT DEFAULT 0 NOT NULL;
ALTER TABLE app_user ADD COLUMN locked_until TIMESTAMP WITH TIME ZONE;

-- 2. Create user_scope table supporting many IP/asset/application mappings per user
CREATE TABLE user_scope (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    ip_address VARCHAR(50),
    application_name VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_user_scope_user FOREIGN KEY (user_id) REFERENCES app_user(id) ON DELETE CASCADE
);

CREATE INDEX idx_user_scope_user_id ON user_scope(user_id);
CREATE INDEX idx_user_scope_ip_address ON user_scope(ip_address);
CREATE INDEX idx_user_scope_app_name ON user_scope(application_name);
CREATE INDEX idx_user_scope_lookup ON user_scope(user_id, ip_address, application_name);
